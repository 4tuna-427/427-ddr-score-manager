#!/usr/bin/env python3
"""songs_v2.json から D1 用シードSQL (songs/charts) を生成する。
使い方: python3 make_seed.py [v2.jsonパス] [出力SQLパス]
適用: wrangler d1 execute ddr-score-db --remote --file seed_master.sql
"""
import json, re, sys, unicodedata, time
from pathlib import Path

src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home()/"workspace/ddr-data-pipeline/phase3/out/songs_v2.json"
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).parent/"seed_master.sql"

def normalize(title):
    if not title: return ""
    t = unicodedata.normalize("NFKC", title).replace("​","").replace("﻿","")
    return re.sub(r"[\s\-_・.,!?'\"“”‘’()（）\[\]【】/\\:：;；]", "", t).lower()

def q(v):
    if v is None: return "NULL"
    if isinstance(v,(int,float)): return str(v)
    return "'" + str(v).replace("'","''") + "'"

KEYMAP = [("sp_beginner","SP","BEGINNER"),("sp_basic","SP","BASIC"),("sp_difficult","SP","DIFFICULT"),
          ("sp_expert","SP","EXPERT"),("sp_challenge","SP","CHALLENGE"),
          ("dp_basic","DP","BASIC"),("dp_difficult","DP","DIFFICULT"),
          ("dp_expert","DP","EXPERT"),("dp_challenge","DP","CHALLENGE")]
songs = json.loads(src.read_text(encoding="utf-8"))
now = int(time.time()*1000)
lines = ["-- generated by make_seed.py from songs_v2.json", f"-- songs: {len(songs)}"]
ns=nc=0
for s in songs:
    lines.append("INSERT OR REPLACE INTO songs (song_id,title,title_normalized,artist,version,bpm,phash_8,phash_16,availability,deleted_at,updated_at) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%d);" % (
        q(s["id"]), q(s["title"]), q(normalize(s["title"])), q(s.get("artist") or None),
        q(s.get("version_current") or s.get("version_remy_first_ddr") or None), q(s.get("bpm") or None),
        q(s.get("phash_8") or None), q(s.get("phash_16") or None), q(s.get("availability") or "standard"),
        q(s.get("deleted_at") or None), now))
    ns+=1
    levels = s.get("levels") or {}; ncs = s.get("notecounts") or {}
    for key, style, diff in KEYMAP:
        lv = levels.get(key)
        if lv is None: continue
        n = ncs.get(key) or {}
        notes, freeze, shock = n.get("notes"), n.get("freeze"), n.get("shock")
        def _i(x):
            try: return int(x)
            except (TypeError, ValueError): return None
        notes, freeze, shock = _i(notes), _i(freeze), _i(shock)
        max_ex = (notes+freeze)*3 if notes is not None and freeze is not None else None
        cid = f"{s['id']}|{style}|{diff}"
        lines.append("INSERT OR REPLACE INTO charts (chart_id,song_id,play_style,difficulty,level,notes,freeze,shock,max_ex) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s);" % (
            q(cid), q(s["id"]), q(style), q(diff), q(lv), q(notes), q(freeze), q(shock), q(max_ex)))
        nc+=1
out.write_text("\n".join(lines)+"\n", encoding="utf-8")
print(f"songs={ns} charts={nc} -> {out} ({out.stat().st_size/1e6:.1f} MB)")
